#!/usr/bin/env python3
"""Borealis shaderdb & ggml-agx ISA/GPR/spill auditor.

Enforces Pillar 1 hardware occupancy invariants across all AGX3 compute kernels:
  1. 0:0 spills/fills across 100% of kernels (hard gate).
  2. Hot kernels <= 96 32-bit GPRs (<= 192 16-bit half-GPRs in Borealis shaderdb)
     so >= 20-32 simdgroups/core stay resident on M4 Max AGX3.

Parses both:
  - Mesa Borealis `AGX_MESA_DEBUG=shaderdb` stderr lines
  - `ggml-agx` internal compiler log lines (`[agx-compiler] kernel=... gprs=... spills=...`)

Usage:
    audit_shaderdb.py [--max-gpr32 96] [--markdown out.md] <shaderdb.log> [...]
"""
import argparse
import re
import sys
from pathlib import Path

# Example Borealis shaderdb line (generated by process_shader_stats.py):
#   CS shader: 142 instrs, 48 alu, 12 fscib, 8 ic, 96 gprs, 768 threads, 0:0 spills:fills, 0 scratch, 840 bytes, 1 loops
RE_BOREALIS = re.compile(
    r"(?P<stage>[A-Z]{2,4})\s+shader:\s*"
    r"(?P<rest>.+)"
)
RE_AGX_INTERNAL = re.compile(
    r"\[agx-compiler\]\s+kernel=(?P<name>\S+)\s+(?P<rest>.+)"
)

RE_INSTRS = re.compile(r"(?:\binstrs?=(?P<v1>\d+)|\b(?P<v2>\d+)\s+instrs?\b(?!\s*=))")
RE_GPRS = re.compile(r"(?:\b(?:gpr32|gpr16|half_gprs|gprs?)=(?P<v1>\d+)|\b(?P<v2>\d+)\s+gprs?\b(?!\s*=))")
RE_THREADS = re.compile(r"(?:\bthreads?=(?P<v1>\d+)|\b(?P<v2>\d+)\s+threads?\b(?!\s*=))")
RE_SPILLS_COLON = re.compile(r"\b(?P<spills>\d+):(?P<fills>\d+)\s+spills(?::fills)?\b")
RE_SPILLS_EQ = re.compile(r"\bspills=(?P<spills>\d+)(?:\s+fills=(?P<fills>\d+))?")
RE_SCRATCH = re.compile(r"(?:\bscratch=(?P<v1>\d+)|\b(?P<v2>\d+)\s+scratch\b(?!\s*=))")
RE_BYTES = re.compile(r"(?:\bbytes=(?P<v1>\d+)|\b(?P<v2>\d+)\s+bytes?\b(?!\s*=))")


def _extract_int(rx, s, default=0):
    m = rx.search(s)
    if not m:
        return default
    for g in ("v", "v1", "v2"):
        if g in m.groupdict() and m.group(g) is not None:
            return int(m.group(g))
    return default


def parse_log(text: str):
    rows = []
    shader_idx = 0
    for line in text.splitlines():
        m_int = RE_AGX_INTERNAL.search(line)
        if m_int:
            rest = m_int.group("rest")
            name = m_int.group("name")
            ms = RE_SPILLS_EQ.search(rest) or RE_SPILLS_COLON.search(rest)
            spills = int(ms.group("spills")) if ms else 0
            fills = int(ms.group("fills") or 0) if ms else 0
            gprs = _extract_int(RE_GPRS, rest, 0)
            # Internal agx-compiler reports 32-bit GPRs if tagged gpr32=, otherwise half-GPRs if gpr16=
            is_half = ("gpr16=" in rest) or ("half_gprs=" in rest)
            gpr32 = (gprs + 1) // 2 if is_half else gprs
            rows.append({
                "name": name,
                "source": "agx-compiler",
                "instrs": _extract_int(RE_INSTRS, rest, 0),
                "gpr_raw": gprs,
                "gpr32": gpr32,
                "threads": _extract_int(RE_THREADS, rest, 0),
                "spills": spills,
                "fills": fills,
                "scratch": _extract_int(RE_SCRATCH, rest, 0),
                "bytes": _extract_int(RE_BYTES, rest, 0),
            })
            continue

        m_b = RE_BOREALIS.search(line)
        if m_b:
            shader_idx += 1
            rest = m_b.group("rest")
            ms = RE_SPILLS_COLON.search(rest) or RE_SPILLS_EQ.search(rest)
            spills = int(ms.group("spills")) if ms else 0
            fills = int(ms.group("fills") or 0) if ms else 0
            gprs_half = _extract_int(RE_GPRS, rest, 0)
            # Borealis agx2_stats.gprs counts 16-bit half-registers (r0l..r127h, max 256 -> 128 32-bit GPRs)
            gpr32 = (gprs_half + 1) // 2
            rows.append({
                "name": f"{m_b.group('stage')}#{shader_idx}",
                "source": "borealis",
                "instrs": _extract_int(RE_INSTRS, rest, 0),
                "gpr_raw": gprs_half,
                "gpr32": gpr32,
                "threads": _extract_int(RE_THREADS, rest, 0),
                "spills": spills,
                "fills": fills,
                "scratch": _extract_int(RE_SCRATCH, rest, 0),
                "bytes": _extract_int(RE_BYTES, rest, 0),
            })
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("logs", nargs="+", type=Path)
    ap.add_argument("--max-gpr32", type=int, default=96)
    ap.add_argument("--markdown", type=Path, default=None)
    args = ap.parse_args()

    all_rows = []
    for p in args.logs:
        all_rows.extend(parse_log(p.read_text(errors="replace")))

    if not all_rows:
        print("FAIL: No shaderdb or [agx-compiler] entries found in input logs.", file=sys.stderr)
        return 2

    spill_fails = [r for r in all_rows if r["spills"] > 0 or r["fills"] > 0 or r["scratch"] > 0]
    gpr_fails = [r for r in all_rows if r["gpr32"] > args.max_gpr32]

    lines = [
        "| Kernel | Source | Instrs | GPRs (32b) | Threads | Spills:Fills | Scratch | Bytes | Status |",
        "|---|---|---:|---:|---:|---:|---:|---:|---|",
    ]
    for r in all_rows:
        ok = (r["spills"] == 0 and r["fills"] == 0 and r["scratch"] == 0 and r["gpr32"] <= args.max_gpr32)
        st = "PASS" if ok else "FAIL"
        lines.append(
            f"| `{r['name']}` | {r['source']} | {r['instrs']} | {r['gpr32']} | {r['threads']} | "
            f"{r['spills']}:{r['fills']} | {r['scratch']} | {r['bytes']} | {st} |"
        )
    table = "\n".join(lines)
    print(table)
    if args.markdown:
        args.markdown.write_text(table + "\n")

    print(f"\nSummary: {len(all_rows)} kernels audited | spill_fails={len(spill_fails)} | gpr32>{args.max_gpr32}={len(gpr_fails)}")
    if spill_fails or gpr_fails:
        return 1
    print("PASS: 0:0 spills across 100% of kernels and all GPR budgets satisfied.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
